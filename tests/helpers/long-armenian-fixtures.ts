/** Spec for a draft section. */
export interface LongSectionSpec {
  sectionType: SectionType;
  title: string;
  /** Body text. May include `\n\n` paragraph breaks + inline `[F1]`/`[L1]`/... */
  text: string;
  /** Internal source ids this section cites (F1, CE1, L1, C1, CC1, E1, A1). */
  sourceIds: string[];
  /** Optional sub-paragraphs (numbered for requested_relief, bulleted else). */
  paragraphs?: string[];
  /** Optional table (rendered as ASCII in TXT, real table in DOCX/PDF). */
  table?: { headers: string[]; rows: string[][] };
}

/** Spec for a case document (creates a CaseDocument row + an E-id in the map). */
export interface LongDocumentSpec {
  displayName: string;
  documentType: string;
  pageCount: number;
  /** Optional; if set, an E-id is created pointing to this document. */
  evidenceSourceId?: string;
  /** Citation rendered in the References section + as inline replacement. */
  evidenceCitation?: string;
}

export interface LongFixtureExpected {
  /** Case number string (must appear in TXT/DOCX/PDF export). */
  caseNumber: string;
  /** Material fact propositions (must appear in export). */
  facts: string[];
  /** Statute citations (must appear in export). */
  statutes: string[];
  /** Cassation decision numbers (must appear). */
  cassationPrecedents: string[];
  /** ConCourt decision numbers (must appear). */
  conCourtPrecedents: string[];
  /** ECHR application / case citations (must appear). */
  echrPrecedents: string[];
  /** Requested relief propositions (must appear). */
  requestedRelief: string[];
  /** Attachment display names (must appear in attachment list). */
  attachmentNames: string[];
  /** Approximate lower-bound on total body char count (for length assertions). */
  minTotalChars: number;
}

export interface LongArmenianFixture {
  fixtureId: LongFixtureId;
  documentType: DocumentType;
  caseId: string;
  draftId: string;
  versionId: string;
  /** Verification status of the DraftVersion. */
  verificationStatus: "UNVERIFIED" | "VERIFIED";
  /** SourceIdMap persisted on the DraftVersion. */
  sourceIdMap: SourceIdMap;
  /** Sections that were persisted (for export + verification). */
  sections: LongSectionSpec[];
  /** Strings the visual-QA test should expect to find in the export. */
  expected: LongFixtureExpected;
  /** §19 archive-first cleanup. NEVER throws. */
  cleanup: () => Promise<void>;
}

