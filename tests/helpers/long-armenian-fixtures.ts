/**
 * Create a real persisted CaseWorkspace + CaseDocument + LegalDraft +
 * DraftVersion + DraftSection row set with rich Armenian legal prose, ready
 * to be exported via `exportDraft(draftId, versionId, format)`.
 *
 * @param id one of the 5 LongFixtureIds
 * @returns LongArmenianFixture — see interface above
 */
export async function createLongArmenianFixture(
  id: LongFixtureId,
): Promise<LongArmenianFixture> {
  const def = FIXTURES[id];
  if (!def) {
    throw new Error(
      `Unknown long-armenian fixture: ${id}. Known: ${Object.keys(FIXTURES).join(", ")}`,
    );
  }

  const suffix = randomBytes(4).toString("hex");
  const now = new Date();
  const caseId = `case-vqa-${id.toLowerCase()}-${suffix}`;
  const draftId = `draft-vqa-${id.toLowerCase()}-${suffix}`;
  const versionId = `version-vqa-${id.toLowerCase()}-${suffix}`;

  // §11 — Create the case with captured identity.
  await db.caseWorkspace.create({
    data: {
      id: caseId,
      title: `${def.caseTitle} [${suffix}]`,
      caseType: def.caseType,
      jurisdiction: def.jurisdiction,
      court: def.court,
      proceedingType: def.proceedingType,
      status: "ACTIVE",
      documentCount: def.documents.length,
      pageCount: def.documents.reduce((s, d) => s + d.pageCount, 0),
      createdAt: now,
      updatedAt: now,
    },
  });

  const documentIdMap: Record<string, string> = {};

  try {
    // §28 — Create CaseDocument rows (for the attachment list).
    for (let i = 0; i < def.documents.length; i++) {
      const d = def.documents[i];
      const docId = `doc-vqa-${id.toLowerCase()}-${i}-${suffix}`;
      await db.caseDocument.create({
        data: {
          id: docId,
          caseId,
          volumeId: null,
          originalFilename: `${d.displayName}.pdf`,
          displayName: d.displayName,
          mimeType: "application/pdf",
          sizeBytes: 1024 * (i + 1) * 100,
          sha256: `sha-vqa-${id}-${i}-${suffix}`,
          documentType: d.documentType,
          pageCount: d.pageCount,
          processingStatus: "READY",
          requiresOcr: false,
          storageKey: `storage/vqa-${id}/${docId}`,
          createdAt: now,
          updatedAt: now,
        },
      });
      if (d.evidenceSourceId) {
        documentIdMap[d.evidenceSourceId] = docId;
      }
    }

    // §10 — Build the SourceIdMap with citations, then patch evidence refs.
    const sourceIdMap = buildSourceIdMap(def);
    for (const doc of def.documents) {
      if (doc.evidenceSourceId && sourceIdMap[doc.evidenceSourceId]) {
        sourceIdMap[doc.evidenceSourceId].refId = documentIdMap[doc.evidenceSourceId];
      }
    }

    // §11 — Create LegalDraft row.
    await db.legalDraft.create({
      data: {
        id: draftId,
        caseId,
        documentType: def.documentType,
        title: def.caseTitle,
        status: def.verificationStatus === "VERIFIED" ? "EXPORT_READY" : "DRAFTING",
        language: "hy",
        targetCourtOrAuthority: def.court,
        proceduralStage: def.proceedingType,
        filingDeadline: null,
        goal: def.goal,
        requestedRelief: def.requestedRelief,
        contextSummary: JSON.stringify({ fixtureId: id, suffix }),
        plan: JSON.stringify({}),
        parties: JSON.stringify(def.parties),
        jurisdiction: def.jurisdiction,
        caseNumber: def.caseNumber,
        createdAt: now,
        updatedAt: now,
      },
    });

    // §10 — Create DraftVersion row.
    await db.draftVersion.create({
      data: {
        id: versionId,
        draftId,
        version: 1,
        content: JSON.stringify(def.sections),
        createdBy: "SYSTEM",
        verificationStatus: def.verificationStatus,
        sourceIdMap: JSON.stringify(sourceIdMap),
        createdAt: now,
        updatedAt: now,
      },
    });

    // §12 — Create DraftSection rows.
    for (let i = 0; i < def.sections.length; i++) {
      const s = def.sections[i];
      const content = {
        text: s.text,
        sourceIds: s.sourceIds,
        ...(s.paragraphs ? { paragraphs: s.paragraphs } : {}),
        ...(s.table ? { table: s.table } : {}),
      };
      await db.draftSection.create({
        data: {
          id: `sec-vqa-${id.toLowerCase()}-${i}-${suffix}`,
          draftId,
          versionId,
          sectionType: s.sectionType,
          title: s.title,
          content: JSON.stringify(content),
          reviewStatus: "VERIFIED",
          stale: false,
          warnings: "[]",
          previousContent: null,
          createdAt: now,
          updatedAt: now,
        },
      });
    }

    return {
      fixtureId: def.fixtureId,
      documentType: def.documentType,
      caseId,
      draftId,
      versionId,
      verificationStatus: def.verificationStatus,
      sourceIdMap,
      sections: def.sections,
      expected: def.expected,
      cleanup: () => safeCleanup(caseId),
    };
  } catch (err) {
    await safeCleanup(caseId);
    throw err;
  }
}
