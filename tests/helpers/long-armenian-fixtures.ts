// -------------------------------------------------------------------------
// SourceIdMap construction (per fixture — based on cited IDs)
// -------------------------------------------------------------------------

/**
 * Build a SourceIdMap for the fixture based on which internal source ids are
 * actually cited in the sections + documents. The citation text uses the
 * Armenian human-readable form (so §10: "normal export renders human-readable
 * legal citations, NOT debug IDs").
 */
function buildSourceIdMap(def: FixtureDef): SourceIdMap {
  const map: SourceIdMap = {};

  // F-ids (facts) — derived from sections.facts sourceIds.
  // CE-ids (chronology) — derived from procedural_history + introduction.
  // L-ids (legislation) — from applicable_law + others.
  // C-ids (cassation) — from precedents where the citation form is cassation.
  // CC-ids (concourt) — from precedents where the citation form is concourt.
  // E-ids (echr) — from precedents + evidence documents.

  // Collect every cited id across all sections.
  const citedIds = new Set<string>();
  for (const section of def.sections) {
    for (const id of section.sourceIds) citedIds.add(id);
  }

  // Build citations for F-ids.
  // F-id → derived from def.sections.facts.
  let fIdx = 0;
  for (const section of def.sections) {
    if (section.sectionType !== "facts") continue;
    for (const id of section.sourceIds) {
      // Match F\d+ (F1, F2, ...) — exclude "F\u0530..." Armenian forms.
      if (/^F\d+$/.test(id) && !map[id]) {
        const idx = parseInt(id.slice(1), 10) || ++fIdx;
        map[id] = {
          type: "fact",
          refId: `${def.fixtureId}-fact-${idx}`,
          citation: `Փաստ ${id} (${def.fixtureId})`,
        };
      }
    }
  }

  // CE-ids (chronology).
  for (const section of def.sections) {
    if (section.sectionType !== "procedural_history") continue;
    for (const id of section.sourceIds) {
      if (id.startsWith("CE") && !map[id]) {
        const idx = parseInt(id.slice(2), 10) || 1;
        map[id] = {
          type: "chronology",
          refId: `${def.fixtureId}-chronology-${idx}`,
          citation: `Ժամանակագրական իրադարձություն ${idx} (${def.fixtureId})`,
        };
      }
    }
  }

  // L-ids (legislation).
  const legislationMap: Record<string, string> = {
    L1: def.expected.statutes[0] ?? "ՀՀ օրենսդրություն",
    L2: def.expected.statutes[1] ?? "ՀՀ օրենսդրություն",
    L3: def.expected.statutes[2] ?? "ՀՀ օրենսդրություն",
    L4: def.expected.statutes[3] ?? "ՀՀ օրենսդրություն",
  };
  for (const id of citedIds) {
    if (/^L\d+$/.test(id) && !map[id]) {
      const idx = parseInt(id.slice(1), 10) || 1;
      map[id] = {
        type: "legislation",
        refId: `${def.fixtureId}-leg-${idx}`,
        citation: legislationMap[id] ?? `ՀՀ օրենսդրություն ${idx}`,
      };
    }
  }

  // C-ids (cassation). Match C\d+ but NOT CC\d+ or CE\d+.
  let cIdx = 0;
  for (const id of citedIds) {
    if (/^C\d+$/.test(id) && !map[id]) {
      const citation = def.expected.cassationPrecedents[cIdx] ?? `ՎճԻՆԱ/0000/2022`;
      cIdx++;
      map[id] = {
        type: "cassation",
        refId: `${def.fixtureId}-cass-${id}`,
        citation,
      };
    }
  }

  // CC-ids (concourt).
  let ccIdx = 0;
  for (const id of citedIds) {
    if (/^CC\d+$/.test(id) && !map[id]) {
      const citation = def.expected.conCourtPrecedents[ccIdx] ?? `ՍԴՈ/0000/2020`;
      ccIdx++;
      map[id] = {
        type: "concourt",
        refId: `${def.fixtureId}-concourt-${id}`,
        citation,
      };
    }
  }

  // A-ids (argument).
  for (const id of citedIds) {
    if (/^A\d+$/.test(id) && !map[id]) {
      map[id] = {
        type: "argument",
        refId: `${def.fixtureId}-arg-${id}`,
        citation: `Փաստարկություն ${id} (${def.fixtureId})`,
      };
    }
  }

  // E-ids (echr + evidence). E-ids can refer to either ECHR precedents OR
  // evidence documents. The fixture's documents[] declares which E-ids are
  // evidence documents; the rest default to ECHR precedents.
  for (const doc of def.documents) {
    if (doc.evidenceSourceId) {
      map[doc.evidenceSourceId] = {
        type: "evidence",
        refId: `evidence-${doc.displayName.replace(/\s+/g, "-")}`,
        citation: doc.evidenceCitation ?? doc.displayName,
      };
    }
  }
  // E-ids not yet filled = ECHR precedents (E1, E5, E6, E7, ...).
  let eIdx = 0;
  for (const id of citedIds) {
    if (/^E\d+$/.test(id) && !map[id]) {
      const citation = def.expected.echrPrecedents[eIdx] ?? `ՄԻԵՎ հայց թիվ 00000/00`;
      eIdx++;
      map[id] = {
        type: "echr",
        refId: `${def.fixtureId}-echr-${id}`,
        citation,
      };
    }
  }

  return map;
}

// -------------------------------------------------------------------------
// §19 — archive-first cleanup (NEVER throws)
// -------------------------------------------------------------------------

async function safeCleanup(caseId: string): Promise<void> {
  try {
    await db.draftSection.deleteMany({ where: { draftId: { startsWith: `draft-${caseId.slice(-12)}` } } });
  } catch {
    // ignore
  }
  try {
    await db.draftVersion.deleteMany({ where: { draftId: { startsWith: `draft-${caseId.slice(-12)}` } } });
  } catch {
    // ignore
  }
  try {
    await db.legalDraft.deleteMany({ where: { caseId } });
  } catch {
    // ignore
  }
  try {
    await db.caseDocument.deleteMany({ where: { caseId } });
  } catch {
    // ignore
  }
  try {
    await db.caseWorkspace.delete({ where: { id: caseId } });
  } catch {
    // ignore — fall through to nothing more we can do
  }
}

